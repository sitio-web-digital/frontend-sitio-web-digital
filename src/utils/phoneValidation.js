const AREA_CODES_2 = new Set(['11']);

export function validateArgentinePhone(raw) {
  const digits = (raw || '').replace(/\D/g, '');
  if (!digits) return { ok: true, empty: true, digits: '' };
  if (digits.length !== 10) {
    return {
      ok: false,
      error: `Tiene que tener 10 números (código de área + número, sin el 0 ni el 15) — tenés ${digits.length}.`,
    };
  }
  const hasAreaCode =
    AREA_CODES_4.has(digits.slice(0, 4)) || AREA_CODES_3.has(digits.slice(0, 3)) || AREA_CODES_2.has(digits.slice(0, 2));
  if (!hasAreaCode) {
    return { ok: false, error: 'No reconocemos ese código de área de Argentina. Revisá el número.' };
  }
  return { ok: true, empty: false, digits };
}
